package go.email;


public class Attachment {

   private int id;
   private String ordner;


   public int getId() {
      return this.id;
   }

   public void setId(int id) {
      this.id = id;
   }

   public String getOrdner() {
      return this.ordner;
   }

   public void setOrdner(String ordner) {
      this.ordner = ordner;
   }
}
