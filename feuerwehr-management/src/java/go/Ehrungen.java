package go;


public class Ehrungen {

   private int id;
   private int ehrungID;
   private int zeit;


   public int getId() {
      return this.id;
   }

   public void setId(int id) {
      this.id = id;
   }

   public int getEhrungID() {
      return this.ehrungID;
   }

   public void setEhrungID(int ehrungID) {
      this.ehrungID = ehrungID;
   }

   public int getZeit() {
      return this.zeit;
   }

   public void setZeit(int zeit) {
      this.zeit = zeit;
   }
}
