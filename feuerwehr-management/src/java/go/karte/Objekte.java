package go.karte;


public class Objekte {

   private int id;
   private String name;
   private String objektNummer;
   private int straße;
   private String hausnummer;
   private String gefaehrdungen;
   private String beschreibung;
   private String GPS_N;
   private String GPS_O;
   private String ansprechpartner;
   private String bewohner;
   private String personal;
   private String oeffnungszeiten;


   public int getId() {
      return this.id;
   }

   public void setId(int id) {
      this.id = id;
   }

   public String getName() {
      return this.name;
   }

   public void setName(String name) {
      this.name = name;
   }

   public String getObjektNummer() {
      return this.objektNummer;
   }

   public void setObjektNummer(String objektNummer) {
      this.objektNummer = objektNummer;
   }

   public int getStraße() {
      return this.straße;
   }

   public void setStraße(int straße) {
      this.straße = straße;
   }

   public String getGefaehrdungen() {
      return this.gefaehrdungen;
   }

   public void setGefaehrdungen(String gefaehrdungen) {
      this.gefaehrdungen = gefaehrdungen;
   }

   public String getBeschreibung() {
      return this.beschreibung;
   }

   public void setBeschreibung(String beschreibung) {
      this.beschreibung = beschreibung;
   }

   public String getGPS_N() {
      return this.GPS_N;
   }

   public void setGPS_N(String gPS_N) {
      this.GPS_N = gPS_N;
   }

   public String getGPS_O() {
      return this.GPS_O;
   }

   public void setGPS_O(String gPS_O) {
      this.GPS_O = gPS_O;
   }

   public String getHausnummer() {
      return this.hausnummer;
   }

   public void setHausnummer(String hausnummer) {
      this.hausnummer = hausnummer;
   }

   public String getAnsprechpartner() {
      return this.ansprechpartner;
   }

   public void setAnsprechpartner(String ansprechpartner) {
      this.ansprechpartner = ansprechpartner;
   }

   public String getBewohner() {
      return this.bewohner;
   }

   public void setBewohner(String bewohner) {
      this.bewohner = bewohner;
   }

   public String getPersonal() {
      return this.personal;
   }

   public void setPersonal(String personal) {
      this.personal = personal;
   }

   public String getOeffnungszeiten() {
      return this.oeffnungszeiten;
   }

   public void setOeffnungszeiten(String oeffnungszeiten) {
      this.oeffnungszeiten = oeffnungszeiten;
   }
}
